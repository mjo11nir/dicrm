export function HelpScreen(params, nav) {
  const root = el('div', { class: 'page' },
    navBar({ title: 'Помощь', onBack: () => nav.pop() }),
    el('div', { class: 'page-body' },
      el('div', { class: 'group-header' }, 'Как установить на iPhone'),
      el('div', { class: 'card help-card' },
        el('ol', {},
          el('li', {}, 'Откройте приложение в Safari.'),
          el('li', {}, 'Нажмите кнопку «Поделиться» (квадрат со стрелкой вверх).'),
          el('li', {}, 'Выберите «На экран „Домой“» и нажмите «Добавить».'),
          el('li', {}, 'Запускайте приложение с иконки — оно откроется на весь экран.'))),
      el('div', { class: 'group-header' }, 'Вопросы и ответы'),
      ...FAQ.map(([q, a]) => el('details', { class: 'card faq' }, el('summary', {}, q), el('p', {}, a)))));
  return { el: root };
}
